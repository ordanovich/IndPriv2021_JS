export const STRINGS = { es, en };

export const fmtInt = (lang, n) => n.toLocaleString(STRINGS[lang].locale);
export const fmtNum = (lang, n, d = 2) =>
  n == null || !Number.isFinite(n) ? "—"
    : n.toLocaleString(STRINGS[lang].locale, { minimumFractionDigits: d, maximumFractionDigits: d });
